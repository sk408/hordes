#!/usr/bin/env node
// HORDES: writes the GENERATED block of sw.js from the tree: VERSION, FILES (path -> SHA-256) and MUSIC.
//   node tools/gen_sw.mjs                  rewrite the block if it changed (keeps sw.js's line endings)
//   node tools/gen_sw.mjs --check          exit 1 if the block is stale (lists what changed)
//   node tools/gen_sw.mjs --root <dir>     act on another worktree (the release worktree)
//   node tools/gen_sw.mjs --print-version  print VERSION
// test/test_sw_manifest.mjs runs the same check in the suite. The design is in sw.js's header
// and docs/CHECKPOINT.md ("How a release is made").
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TEXT = /\.(?:html|js|mjs|css|json|webmanifest|svg|txt)$/;   // same list as sw.js
export const BEGIN = '// ---- GENERATED by tools/gen_sw.mjs';
export const END = '// ---- end GENERATED ----';
export const KILL_MARK = '// HORDES KILL SWITCH';
export const MUSIC_RE = /^assets\/music\/[a-z0-9_]+\.([0-9a-f]{8})\.mp3$/;
export const FORBIDDEN = /^(?:docs|tools|test|classic)\/|^assets\/music\/|^(?:editor\.html|sw\.js)$|\.md$/;
const sha = (b) => createHash('sha256').update(b).digest('hex');

// The precache rule: the page, its manifest, every file under src/, and every file under assets/
// except the music (cached on demand) and notes (*.md).
export function precachePaths(root = ROOT) {
  const out = ['index.html', 'manifest.webmanifest'];
  const walk = (dir) => {
    if (!fs.existsSync(path.join(root, dir))) return;
    for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const p = dir + '/' + e.name;
      if (e.isDirectory()) walk(p); else out.push(p);
    }
  };
  walk('src'); walk('assets');
  const list = out.filter((p) => !p.startsWith('assets/music/') && !p.endsWith('.md'))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const p of list) if (FORBIDDEN.test(p)) throw new Error('precache rule picked a forbidden path: ' + p);
  return list;
}
export function lf(buf) {          // CRLF -> LF as git does; a lone CR stays
  const out = Buffer.allocUnsafe(buf.length); let j = 0;
  for (let i = 0; i < buf.length; i++) { if (buf[i] === 13 && buf[i + 1] === 10) continue; out[j++] = buf[i]; }
  return out.subarray(0, j);
}
export const fileHash = (p, bytes) => sha(TEXT.test(p) ? lf(bytes) : bytes);
export function split(sw) {        // -> { before, block, after } of the LF-normalised text
  const t = sw.replace(/\r\n/g, '\n');
  const a = t.indexOf(BEGIN); const b = t.indexOf(END);
  if (a < 0 || b < a || t.indexOf(BEGIN, a + 1) >= 0 || t.indexOf(END, b + 1) >= 0) throw new Error('sw.js needs exactly one GENERATED block');
  return { before: t.slice(0, a), block: t.slice(a, b + END.length), after: t.slice(b + END.length) };
}
export const coreHash = (sw) => { const s = split(sw); return sha(s.before + s.after); };
export const computeVersion = (files, core) =>
  sha(files.map(([p, h]) => p + ' ' + h + '\n').join('') + 'core ' + core + '\n').slice(0, 12);
export async function musicUrls(root = ROOT) {
  // Node caches an import per URL: the query (the file's own hash) makes a rewritten manifest
  // (tools/music_import.mjs, in the same process) load fresh.
  const man = path.join(root, 'src/music_manifest.js');
  const { MUSIC_TRACKS } = await import(pathToFileURL(man).href + '?h=' + sha(fs.readFileSync(man)).slice(0, 16));
  const urls = Object.values(MUSIC_TRACKS).map((t) => t.url).sort();
  for (const u of urls) {
    const m = MUSIC_RE.exec(u);
    if (!m) throw new Error('music url does not match <slot>.<hash8>.mp3: ' + u);
    const f = path.join(root, u);
    if (!fs.existsSync(f)) throw new Error('music_manifest.js names a missing file: ' + u);
    if (sha(fs.readFileSync(f)).slice(0, 8) !== m[1]) throw new Error('music file does not match its name: ' + u);
  }
  return urls;
}
export function renderBlock({ version, files, music }) {
  return [BEGIN + ' from the tree: do not edit. Run node tools/gen_sw.mjs after changing any precached file. ----',
    "const VERSION = '" + version + "';",
    'const FILES = {', ...files.map(([p, h]) => "  '" + p + "': '" + h + "',"), '};',
    'const MUSIC = [', ...music.map((m) => "  '" + m + "',"), '];',
    END].join('\n');
}
export function parseBlock(block) {   // the values currently in sw.js, for --check's diff
  return new Function(block + '\nreturn { VERSION, FILES, MUSIC };')();
}
export async function build(root = ROOT) {
  const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
  const norm = (s) => s.replace(/\r\n/g, '\n');
  if (sw.includes(KILL_MARK)) {
    const kill = fs.readFileSync(path.join(root, 'tools/sw_killswitch.js'), 'utf8');
    return { kill: true, current: norm(sw) === norm(kill) };
  }
  const files = precachePaths(root).map((p) => [p, fileHash(p, fs.readFileSync(path.join(root, p)))]);
  const music = await musicUrls(root);
  const version = computeVersion(files, coreHash(sw));
  const { before, block, after } = split(sw);
  const fresh = renderBlock({ version, files, music });
  const eol = sw.includes('\r\n') ? '\r\n' : '\n';
  return { kill: false, version, files, music, current: block === fresh, old: parseBlock(block),
    text: (before + fresh + after).replace(/\n/g, eol) };
}
// What changed between the block in sw.js and the tree (for --check and the suite's message).
export function staleReport(r) {
  const old = (r.old && r.old.FILES) || {};
  const now = Object.fromEntries(r.files);
  const added = Object.keys(now).filter((p) => !(p in old));
  const removed = Object.keys(old).filter((p) => !(p in now));
  const changed = Object.keys(now).filter((p) => p in old && old[p] !== now[p]);
  const musicChanged = JSON.stringify((r.old && r.old.MUSIC) || []) !== JSON.stringify(r.music);
  const lines = [];
  for (const p of added) lines.push('  added    ' + p);
  for (const p of removed) lines.push('  removed  ' + p);
  for (const p of changed) lines.push('  changed  ' + p);
  if (musicChanged) lines.push('  music    the MUSIC list changed');
  if (!lines.length) lines.push('  core changed (the worker code outside the GENERATED block)');
  return lines;
}

async function cli(argv) {
  const ri = argv.indexOf('--root');
  const root = ri >= 0 ? path.resolve(argv[ri + 1]) : ROOT;
  const r = await build(root);
  if (argv.includes('--print-version')) { console.log(r.kill ? 'KILL' : r.version); return 0; }
  if (argv.includes('--check')) {
    if (r.kill) {
      if (r.current) { console.log('sw.js is the KILL SWITCH'); return 0; }
      console.log('sw.js has the kill mark but is not tools/sw_killswitch.js: copy the file over sw.js exactly'); return 1;
    }
    if (r.current) { console.log('sw.js current: VERSION ' + r.version + ', ' + r.files.length + ' files, ' + r.music.length + ' music'); return 0; }
    console.log('sw.js STALE: run node tools/gen_sw.mjs');
    for (const l of staleReport(r)) console.log(l);
    return 1;
  }
  if (r.kill) { console.log('sw.js is the KILL SWITCH: restore sw.js from git first'); return 1; }
  if (!r.current) {
    fs.writeFileSync(path.join(root, 'sw.js'), r.text);
    console.log('sw.js written');
  }
  console.log(r.version);
  return 0;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  cli(process.argv.slice(2)).then((code) => { process.exitCode = code; },
    (err) => { console.error('gen_sw: ' + (err && err.message || err)); process.exitCode = 1; });
}
