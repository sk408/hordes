#!/usr/bin/env node
// HORDES — import the recorded music into the game (music integration, 2026-11-17).
//
//   node tools/music_import.mjs <picks.json>
//
// <picks.json> maps each slot to a final mastered mp3: { "<slot>": "<path>.mp3", ... }.
// Each mp3 has a sibling .json written by master.py (mode, loopStart, loopEnd, bpm,
// seconds or loopSeconds, lufs). Relative paths resolve against the picks file.
//
// The picks file is the WHOLE set: after an import the game knows exactly these
// slots. For each slot the mp3 is copied to assets/music/<slot>.<hash8>.mp3
// (hash8 = first 8 hex of the file's sha256, so a changed file gets a new name
// and the HTTP cache never serves a stale one); hashed files of a slot that is
// gone or changed are removed; src/music_manifest.js is rewritten, and so is the
// slot table in assets/music/CREDITS.md. Idempotent: the same picks give the same
// bytes. MUSIC_TRIM_DB (measured, see the manifest) is kept across imports, and
// so is a slot's `gain` while its file is unchanged.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build as buildSw } from './gen_sw.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MUSIC_DIR = path.join(ROOT, 'assets', 'music');
const MANIFEST = path.join(ROOT, 'src', 'music_manifest.js');
const CREDITS = path.join(MUSIC_DIR, 'CREDITS.md');
export const LOOP_SLOTS = ['title', 'run_wilds', 'run_ash', 'run_bone', 'run_void', 'boss', 'maw', 'escape'];
export const CUE_SLOTS = ['victory', 'gameover', 'portal'];
const ALL_SLOTS = [...LOOP_SLOTS, ...CUE_SLOTS];
const EOL = '\r\n';   // the repo's files are CRLF (git autocrlf=true)

function fail(msg) { console.error('music_import: ' + msg); process.exit(1); }
const r3 = (x) => Math.round(Number(x) * 1000) / 1000;
const r6 = (x) => Math.round(Number(x) * 1e6) / 1e6;

async function readOld() {
  if (!fs.existsSync(MANIFEST)) return { tracks: {}, trim: 0, trimNote: null };
  const mod = await import(pathToFileURL(MANIFEST).href + '?t=' + Date.now());
  const src = fs.readFileSync(MANIFEST, 'utf8');
  // The measured-loudness comment block above MUSIC_TRIM_DB is kept verbatim.
  const m = src.match(/(\/\/ LOUDNESS[\s\S]*?)export const MUSIC_TRIM_DB/);
  return { tracks: mod.MUSIC_TRACKS || {}, trim: Number(mod.MUSIC_TRIM_DB) || 0, trimNote: m ? m[1] : null };
}

function entryFor(slot, mp3, meta, old) {
  const kind = LOOP_SLOTS.includes(slot) ? 'loop' : 'cue';
  if (meta.mode && meta.mode !== kind) fail(slot + ': master.py mode is ' + meta.mode + ' but the slot is a ' + kind);
  const bytes = fs.readFileSync(mp3);
  const hash8 = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 8);
  const file = slot + '.' + hash8 + '.mp3';
  const e = { url: 'assets/music/' + file, kind, bpm: Number(meta.bpm) || 0 };
  if (kind === 'loop') {
    e.loopStart = r6(meta.loopStart);
    e.loopEnd = r6(meta.loopEnd);
    if (!(e.loopEnd > e.loopStart && e.loopStart >= 0.4)) fail(slot + ': bad loop points ' + e.loopStart + '..' + e.loopEnd);
    if (!(e.bpm > 0)) fail(slot + ': a loop needs its bpm');
    // EXACT TEMPO (2026-11-17): master.py's bpm is the slot's nominal label (130, 132),
    // while the loop was cut to a whole number of BARS at the music's TRUE tempo (beat
    // tracking + seamcheck), which differs by up to ~0.02% (a 48-bar loop at a
    // nominal 130 measured 192.033 beats = 15 ms off). The game's bar-line maths needs
    // the true tempo, so derive it from the whole bar count and the loop length. A loop
    // more than 0.02 bars from whole is not a clean loop: refuse it.
    const L = e.loopEnd - e.loopStart;
    const bars = L / (240 / e.bpm);
    const whole = Math.round(bars);
    if (whole < 1 || Math.abs(bars - whole) > 0.02) fail(slot + ': the loop is ' + bars.toFixed(4) + ' bars at ' + e.bpm + ' bpm, not a whole number');
    e.bpm = Math.round((whole * 240 / L) * 1e4) / 1e4;
  }
  // Loops carry 0.5 s of post-roll after loopEnd (master.py); cues give their length.
  e.seconds = r3(meta.seconds != null ? meta.seconds : (kind === 'loop' ? e.loopEnd + 0.5 : 0));
  e.gain = old && old.url === e.url && Number.isFinite(old.gain) ? old.gain : 1;
  return { slot, file, bytes, entry: e, src: path.basename(mp3), lufs: meta.lufs };
}

function manifestText(rows, trim, trimNote) {
  const L = [];
  L.push('// GENERATED by tools/music_import.mjs from the picks file; edit the picks, not this file');
  L.push('// (MUSIC_TRIM_DB and its measurement note, and a slot\'s gain, are kept across imports).');
  L.push('// Slot -> recorded track. A slot that is missing here has no recorded track and the game');
  L.push('// plays what it played before (the synth in a run, silence elsewhere). url is relative to');
  L.push('// the page. Loops: loopStart/loopEnd in seconds inside the file (0.5 s pre/post roll),');
  L.push('// a whole number of beats at bpm. gain is a per-slot linear trim on top of MUSIC_TRIM_DB.');
  L.push('export const MUSIC_TRACKS = {');
  for (const r of rows) {
    const e = r.entry;
    const parts = ["url: '" + e.url + "'", "kind: '" + e.kind + "'", 'bpm: ' + e.bpm];
    if (e.kind === 'loop') parts.push('loopStart: ' + e.loopStart, 'loopEnd: ' + e.loopEnd);
    parts.push('seconds: ' + e.seconds, 'gain: ' + e.gain);
    L.push('  ' + r.slot + ': { ' + parts.join(', ') + ' },');
  }
  L.push('};');
  L.push('');
  const note = trimNote ? trimNote.replace(/\r?\n/g, EOL).replace(/(\r\n)+$/, '') : '// LOUDNESS: not measured yet (tools/measure_music_loudness.mjs).';
  return L.join(EOL) + EOL + note + EOL + 'export const MUSIC_TRIM_DB = ' + trim + ';' + EOL;
}

const CREDITS_HEAD = [
  '# Music credits',
  '',
  'The recorded music in this folder was made for HORDES with **Google Lyria 3** through the',
  'Gemini API in November 2026, then cut into seamless loops and cues and mastered to -16 LUFS',
  '(96 kbps MP3). Google claims no ownership of generated output. This music is AI-generated:',
  'Google embeds an inaudible SynthID watermark in the audio it generates (whether it survives',
  'the mastering is not documented), and the original takes carried a C2PA content-credentials',
  'manifest naming them as AI-generated. The mastered files here are re-encoded and do not carry',
  'that manifest.',
  '',
  'The game picks a file by slot (see src/music_manifest.js). File names carry the first 8 hex',
  'digits of the file\'s sha256, so a changed file gets a new name. The table below is rewritten',
  'by `node tools/music_import.mjs <picks.json>`.',
  '',
  'The procedural chiptune synth in src/audio.js is still there: it plays when a slot has no',
  'file, before a file has loaded, and when the player picks MUSIC: CLASSIC SYNTH.',
  '',
  '',
];
const BEGIN = '<!-- slots:begin (generated) -->';
const END = '<!-- slots:end -->';

function creditsText(rows) {
  const t = [BEGIN, '| slot | file | kind | bpm | loop (s) | source |', '|---|---|---|---|---|---|'];
  for (const r of rows) {
    const e = r.entry;
    const loop = e.kind === 'loop' ? r3(e.loopEnd - e.loopStart) : '-';
    t.push('| ' + [r.slot, e.url.replace('assets/music/', ''), e.kind, e.bpm || '-', loop, r.src].join(' | ') + ' |');
  }
  if (!rows.length) t.push('| (none) | | | | | |');
  t.push(END);
  let body;
  if (fs.existsSync(CREDITS)) {
    const old = fs.readFileSync(CREDITS, 'utf8').replace(/\r\n/g, '\n');
    const a = old.indexOf(BEGIN), b = old.indexOf(END);
    body = a >= 0 && b > a ? old.slice(0, a) + t.join('\n') + old.slice(b + END.length) : old.replace(/\n*$/, '\n\n') + t.join('\n') + '\n';
  } else body = CREDITS_HEAD.join('\n') + t.join('\n') + '\n';
  return body.replace(/\r?\n/g, EOL);
}

async function main() {
  const picksPath = process.argv[2];
  if (!picksPath) fail('usage: node tools/music_import.mjs <picks.json>');
  const picks = JSON.parse(fs.readFileSync(picksPath, 'utf8'));
  const base = path.dirname(path.resolve(picksPath));
  const old = await readOld();
  const rows = [];
  for (const slot of ALL_SLOTS) {          // fixed slot order: stable output
    if (!(slot in picks)) continue;
    const mp3 = path.resolve(base, picks[slot]);
    if (!fs.existsSync(mp3)) fail(slot + ': no file ' + mp3);
    const side = mp3.replace(/\.mp3$/i, '.json');
    if (!fs.existsSync(side)) fail(slot + ': no sidecar ' + side);
    rows.push(entryFor(slot, mp3, JSON.parse(fs.readFileSync(side, 'utf8')), old.tracks[slot]));
  }
  for (const k of Object.keys(picks)) if (!ALL_SLOTS.includes(k)) fail('unknown slot ' + k);
  fs.mkdirSync(MUSIC_DIR, { recursive: true });
  const keep = new Set(rows.map((r) => r.file));
  for (const r of rows) {
    const dst = path.join(MUSIC_DIR, r.file);
    if (!fs.existsSync(dst)) fs.writeFileSync(dst, r.bytes);
  }
  // Superseded hashed files: any <slot>.<hash8>.mp3 not in this import.
  for (const f of fs.readdirSync(MUSIC_DIR)) {
    if (/^[a-z_]+\.[0-9a-f]{8}\.mp3$/.test(f) && !keep.has(f)) { fs.unlinkSync(path.join(MUSIC_DIR, f)); console.log('removed ' + f); }
  }
  fs.writeFileSync(MANIFEST, manifestText(rows, old.trim, old.trimNote));
  fs.writeFileSync(CREDITS, creditsText(rows));
  // The service worker's GENERATED block lists the music and hashes the manifest (tools/gen_sw.mjs).
  const sw = await buildSw(ROOT);
  if (!sw.kill && !sw.current) { fs.writeFileSync(path.join(ROOT, 'sw.js'), sw.text); console.log('sw.js regenerated: VERSION ' + sw.version); }
  for (const r of rows) console.log(r.slot.padEnd(10) + ' ' + r.file + '  (' + (r.bytes.length / 1024).toFixed(0) + ' KB, ' + r.lufs + ' LUFS)');
  console.log('manifest: ' + rows.length + ' slot(s), MUSIC_TRIM_DB ' + old.trim);
}
main();
