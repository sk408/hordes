// HORDES — character portraits — 32x32 busts, 2 idle frames each
//
// FORMAT (identical to src/sprites.js): a pixel grid is an array of rows, each
// row an array of integer palette indices, 0 = transparent, 1..9 = palette
// keys. `palette` maps those keys to CSS colours. Consume with the renderer's
// own painter:  renderer.drawGrid(g, asset.grid, asset.palette, x, y)
// `asset.rows` is the SAME data as digit strings ('0' = transparent) for
// tooling that reads text rows; it is DERIVED from the grid, never authored
// twice, so the two forms cannot drift (test/test_art_lint.mjs asserts it).
//
// One portrait per entry in meta.js CHARACTERS: the bust of the field pilot
// (src/character_sprites.js), with the same colours and the same gear, under
// the same top-left light.
//   KNIGHT   open-faced steel helm, red plume, red tabard with the gold cross
//   WITCH    bent pointed hat, violet robe with the amber clasp, cyan-tipped staff
//   ROGUE    green hood, sand scarf over the mouth, leather under the cloak
//   PALADIN  winged gold helm, white plate with the gold cross
// Key 1 is always the ink outline. Idle pair: frame 2 drops the head a pixel
// and blinks.
import { makeFrames } from './format.js';

// Text rows ('.' = transparent, a digit = palette key) to the integer grid.
const P = (rows) => rows.map(r => [...r].map(ch => (ch === '.' ? 0 : +ch)));
// The idle pair. Frame A is the head over the shoulders. In frame B the head
// sinks a pixel (its last row, a repeat of the neck, goes) and the eyes close
// (`blink` maps a head row to its closed-eye version). `prop` is drawn over
// both frames and does not move (the staff).
function bust(head, blink, body, prop) {
  const over = (rows) => !prop ? rows
    : rows.map((r, y) => [...r].map((ch, x) => (prop[y][x] === '.' ? ch : prop[y][x])).join(''));
  const shut = head.map((r, i) => blink[i] || r);
  return [P(over([...head, ...body])), P(over(['.'.repeat(32), ...shut.slice(0, -1), ...body]))];
}

